import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildBandTable, GRID_VERSION, ROW_COUNT } from '../src/grid/spec';

const bands = buildBandTable();
const starts = bands.map((b) => b.startD);
const cols = bands.map((b) => b.cols);
const wrap = (xs: number[]) => {
  const lines: string[] = [];
  for (let i = 0; i < xs.length; i += 12) lines.push('  ' + xs.slice(i, i + 12).join(', ') + ',');
  return lines.join('\n');
};
const out = `// GENERATED by scripts/generate-band-table.ts — do not edit by hand.
// Grid v${GRID_VERSION}: ${ROW_COUNT} rows, ${bands.length} bands per hemisphere.
// Freezing the table keeps every client and server on the exact same grid even
// if their Math.sin/cos differ in the last bit. Changing it is a grid migration.

export const BAND_TABLE_GRID_VERSION = ${GRID_VERSION};

/** Row distance from the equator at which each band starts. */
export const BAND_START_D: readonly number[] = [
${wrap(starts)}
];

/** Columns per row in each band. */
export const BAND_COLS: readonly number[] = [
${wrap(cols)}
];
`;
const target = fileURLToPath(new URL('../src/grid/bandTable.generated.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${bands.length} bands to ${target}`);
